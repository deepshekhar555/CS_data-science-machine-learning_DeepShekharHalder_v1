def plot_exploration(df):
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))

    axes[0, 0].plot(df['day'], df['demand'], color='steelblue', linewidth=1.5)
    for x in [120, 150]:
        axes[0, 0].axvline(x, color='black', linestyle='--', linewidth=1)
    axes[0, 0].set_title('Bike demand over time')
    axes[0, 0].set_xlabel('Day')
    axes[0, 0].set_ylabel('Demand')

    weekday_means = df.groupby('weekday')['demand'].mean().reindex(range(7))
    axes[0, 1].bar(weekday_means.index, weekday_means.values, color='darkorange')
    axes[0, 1].set_title('Average demand by weekday')
    axes[0, 1].set_xlabel('Weekday code')
    axes[0, 1].set_ylabel('Average demand')

    rain_means = df.groupby('rain')['demand'].mean()
    axes[1, 0].bar(rain_means.index.astype(str), rain_means.values, color='royalblue')
    axes[1, 0].set_title('Average demand by rain flag')
    axes[1, 0].set_xlabel('Rain (0=no, 1=yes)')
    axes[1, 0].set_ylabel('Average demand')

    axes[1, 1].scatter(df['temp'], df['demand'], alpha=0.7, s=20, color='seagreen')
    axes[1, 1].set_title('Demand vs temperature')
    axes[1, 1].set_xlabel('Temperature (°C)')
    axes[1, 1].set_ylabel('Demand')

    fig.tight_layout()
    fig.savefig(FIG_DIR / 'exploration.png', dpi=200)
    plt.close(fig)


