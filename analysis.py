import csv
import math
import random
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error

ROOT = Path(__file__).resolve().parent
DATA_DIR = ROOT / 'data'
FIG_DIR = ROOT / 'figures'
DATA_DIR.mkdir(exist_ok=True)
FIG_DIR.mkdir(exist_ok=True)


def generate_dataset():
    random.seed(42)
    rows = []
    for day in range(1, 181):
        weekday = day % 7
        temp = 15 + 10 * math.sin(day / 28) + random.uniform(-2, 2)
        rain = 1 if random.random() < 0.25 else 0
        demand = max(0, round(40 + 2 * temp - 18 * rain + 10 * (weekday < 5) + random.uniform(-8, 8)))
        rows.append({
            'day': day,
            'weekday': weekday,
            'temp': round(temp, 3),
            'rain': rain,
            'demand': demand,
        })
    return pd.DataFrame(rows)


def save_dataset(df):
    path = DATA_DIR / 'bike_demand.csv'
    df.to_csv(path, index=False)
    return path


def add_lag_features(df):
    feature_df = df.copy()
    for lag in [1, 2, 3]:
        feature_df[f'lag{lag}_demand'] = feature_df['demand'].shift(lag)
        feature_df[f'lag{lag}_rain'] = feature_df['rain'].shift(lag)
    feature_df['seasonal_sin'] = np.sin(feature_df['day'] / 28)
    feature_df['seasonal_cos'] = np.cos(feature_df['day'] / 28)
    return feature_df


def compute_baselines(df):
    train = df.iloc[:120].copy()
    val = df.iloc[120:150].copy()
    train_mean = train['demand'].mean()
    baseline_a_mae = mean_absolute_error(val['demand'], np.full(len(val), train_mean))
    prev_values = [df.loc[df['day'] == day - 1, 'demand'].iat[0] for day in val['day']]
    baseline_b_mae = mean_absolute_error(val['demand'], prev_values)
    return { 'train_mean': float(train_mean), 'baseline_a_mae': float(baseline_a_mae), 'baseline_b_mae': float(baseline_b_mae) }


def build_candidate_model(df):
    feature_df = add_lag_features(df)
    train = feature_df.iloc[:120].copy()
    val = feature_df.iloc[120:150].copy()
    for lag in [1, 2, 3]:
        fill_demand = train[f'lag{lag}_demand'].mean()
        fill_rain = 0
        feature_df[f'lag{lag}_demand'] = feature_df[f'lag{lag}_demand'].fillna(fill_demand)
        feature_df[f'lag{lag}_rain'] = feature_df[f'lag{lag}_rain'].fillna(fill_rain)
        train[f'lag{lag}_demand'] = train[f'lag{lag}_demand'].fillna(fill_demand)
        train[f'lag{lag}_rain'] = train[f'lag{lag}_rain'].fillna(fill_rain)
        val[f'lag{lag}_demand'] = val[f'lag{lag}_demand'].fillna(fill_demand)
        val[f'lag{lag}_rain'] = val[f'lag{lag}_rain'].fillna(fill_rain)

    features = ['weekday', 'seasonal_sin', 'seasonal_cos', 'lag1_demand', 'lag1_rain', 'lag2_demand', 'lag2_rain', 'lag3_demand', 'lag3_rain']
    model = LinearRegression()
    model.fit(train[features], train['demand'])
    val_pred = model.predict(val[features])
    val_mae = mean_absolute_error(val['demand'], val_pred)
    return val_mae, model, features


