def main():
    df = generate_dataset()
    save_dataset(df)
    metrics = compute_baselines(df)
    candidate_mae, _, _ = build_candidate_model(df)
    save_templates(metrics, candidate_mae)
    save_evidence(metrics, candidate_mae)
    plot_exploration(df)
    write_readme(metrics, candidate_mae)
    print('Generated dataset and honest benchmark files.')
    print(f"Baseline A MAE: {metrics['baseline_a_mae']:.2f}")
